import { mkdirSync, writeFileSync } from "node:fs";
import type { ManufacturerSpecRecord } from "../../src/manufacturer-specs.js";

/** Write one maker's records as a browser-safe TS module + a crawl report. */
export function writeMakerRecords(maker: string, constName: string, input: ManufacturerSpecRecord[], report: Record<string, unknown>) {
  // One record per year + series + floorplan. Two pages publishing different numbers for the same key = ambiguous → neither is kept.
  const byKey = new Map<string, ManufacturerSpecRecord[]>();
  for (const r of input) { const k = `${r.year}|${r.series}|${r.floorplanCode}`.toUpperCase(); byKey.set(k, [...(byKey.get(k) ?? []), r]); }
  const records: ManufacturerSpecRecord[] = []; const ambiguous: string[] = [];
  for (const [k, rs] of byKey) {
    const distinct = new Set(rs.map((r) => JSON.stringify([r.specs, r.bunkhouse ?? null])));
    if (distinct.size === 1) records.push(rs[0]); else ambiguous.push(`${k}: ${rs.map((r) => r.sourceUrl).join(" vs ")}`);
  }
  report.recordsWritten = records.length; report.ambiguousDropped = ambiguous;
  const sorted = [...records].sort((a, b) => a.series.localeCompare(b.series) || a.year - b.year || a.floorplanCode.localeCompare(b.floorplanCode));
  const src = `/**
 * ${maker} manufacturer specs — GENERATED by scripts/brochure-crawl (do not hand-edit).
 * One record per exact model year + series + floorplan, read from ${maker}'s own
 * floorplan/spec pages (sourceUrl). Fields the page did not publish are omitted.
 */
import type { ManufacturerSpecRecord } from "../manufacturer-specs.js";

export const ${constName}: ManufacturerSpecRecord[] = [
${sorted.map((r) => "  " + JSON.stringify(r)).join(",\n")}
];
`;
  const dir = new URL("../../src/spec-records/", import.meta.url);
  mkdirSync(dir, { recursive: true });
  writeFileSync(new URL(`${maker.toLowerCase().replace(/[^a-z]+/g, "-")}.ts`, dir), src);
  const rdir = new URL("../../data/brochure-crawl/", import.meta.url);
  mkdirSync(rdir, { recursive: true });
  writeFileSync(new URL(`${maker.toLowerCase().replace(/[^a-z]+/g, "-")}.report.json`, rdir), JSON.stringify(report, null, 1) + "\n");
}
