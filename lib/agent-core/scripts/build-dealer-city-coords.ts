/**
 * Regenerates src/dealer-city-coords.ts: a state-qualified city → coordinate
 * table for every dealer / listing city in the snapshot, from the US Census
 * Gazetteer (public domain). Only cities that appear in inventory are kept so
 * the browser bundle stays small. Unlisted cities resolve to null (no
 * distance), never to a state centroid.
 *
 *   curl -O https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_place_national.zip
 *   curl -O https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_cousubs_national.zip
 *   unzip both, then:
 *   pnpm tsx scripts/build-dealer-city-coords.ts <places.txt> <cousubs.txt>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { resolve } from "node:path";
import { cityKey, cityFromDealerName, dealerCityCandidates, listingLocationFromTitle } from "../src/listing-reconcile.js";

const [placesPath, cousubPath] = process.argv.slice(2);
if (!placesPath) throw new Error("usage: build-dealer-city-coords.ts <places.txt> [cousubs.txt]");

const LSAD = /\s+(?:city and borough|consolidated government|metropolitan government|metro government|unified government|urban county|city|town|village|borough|municipality|cdp|township|charter township|plantation|gore|grant|location|purchase|ccd|comunidad|zona urbana)(?:\s*\(balance\))?$/i;
type Row = { key: string; lat: number; lng: number; rank: number };
const gaz = new Map<string, Row>();
function load(path: string, rankBase: number) {
  const lines = readFileSync(path, "utf8").split("\n").slice(1);
  for (const line of lines) {
    const f = line.split("\t");
    if (f.length < 10) continue;
    const st = f[0];
    const name = f[3];
    const lat = Number(f[f.length - 2]), lng = Number(f[f.length - 1]);
    if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue;
    const isCdp = /\bCDP$/.test(name);
    const rank = rankBase + (isCdp ? 1 : 0);
    const names = new Set<string>();
    // Strip exactly one legal suffix: "Salt Lake City city" → "Salt Lake City".
    const base = name.replace(/\s*\(balance\)$/i, "").replace(LSAD, "");
    names.add(base);
    for (const part of base.split(/[-/]/)) if (part.trim().length > 2) names.add(part.trim());
    for (const n of names) {
      const key = cityKey(n, st);
      const prev = gaz.get(key);
      if (!prev || rank < prev.rank) gaz.set(key, { key, lat, lng, rank });
    }
  }
}
load(placesPath, 0);
if (cousubPath) load(cousubPath, 10);

const snapPath = resolve(import.meta.dirname, "../data/inventory.snapshot.json.gz");
// Units are parsed one at a time from the bytes: a large snapshot's text can exceed V8's maximum string length.
function readUnits(buf: Buffer): any[] {
  const key = buf.indexOf('"units":[');
  if (key < 0) return JSON.parse(buf.toString("utf8")).units;
  const out: any[] = []; let i = key + 9; const n = buf.length;
  for (;;) {
    while (i < n && (buf[i] === 0x2c || buf[i] <= 0x20)) i++;
    if (i >= n || buf[i] === 0x5d) break;
    const s = i; let d = 0;
    while (i < n) {
      const b = buf[i];
      if (b === 0x22) { i++; while (i < n && buf[i] !== 0x22) i += buf[i] === 0x5c ? 2 : 1; i++; continue; }
      if (b === 0x7b || b === 0x5b) d++;
      else if (b === 0x7d || b === 0x5d) { d--; if (d === 0) { i++; break; } }
      i++;
    }
    out.push(JSON.parse(buf.toString("utf8", s, i)));
  }
  return out;
}
const snap = { units: readUnits(gunzipSync(readFileSync(snapPath))) };
const wanted = new Set<string>();
for (const u of snap.units) {
  const st = String(u.dealer?.state ?? "").toUpperCase();
  for (const c of dealerCityCandidates(u.dealer?.city)) wanted.add(cityKey(c, st));
  const fromName = cityFromDealerName(u.dealer?.name);
  if (fromName) for (const c of dealerCityCandidates(fromName)) wanted.add(cityKey(c, st));
  const loc = listingLocationFromTitle(u.title);
  if (loc) wanted.add(cityKey(loc.city, loc.state));
}
/**
 * Unincorporated dealer towns the Gazetteer has no place/CDP for (largest
 * unresolved inventory). Approximate town centres; review when adding.
 */
const SUPPLEMENT: Record<string, [number, number]> = {
  "kodak|TN": [35.9773, -83.6168],
  "thornburg|VA": [38.1365, -77.5197],
  "summerfield|FL": [28.9972, -82.0337],
  "joppa|MD": [39.4337, -76.3577],
  "san mateo|FL": [29.6116, -81.5862],
};
const out: Record<string, [number, number]> = {};
for (const [k, v] of Object.entries(SUPPLEMENT)) if (wanted.has(k)) out[k] = v;
for (const k of [...wanted].sort()) {
  const hit = gaz.get(k);
  if (hit && !out[k]) out[k] = [Math.round(hit.lat * 1e4) / 1e4, Math.round(hit.lng * 1e4) / 1e4];
}
const body = Object.entries(out).map(([k, [a, b]]) => `  ${JSON.stringify(k)}: [${a}, ${b}],`).join("\n");
writeFileSync(
  resolve(import.meta.dirname, "../src/dealer-city-coords.ts"),
  `// GENERATED by scripts/build-dealer-city-coords.ts from the US Census 2023 Gazetteer\n// (places, then county subdivisions). Key: cityKey(city, state) → [lat, lng].\n// Do not edit by hand; rerun the script after a harvest adds new dealer cities.\nexport const DEALER_CITY_COORDS: Record<string, readonly [number, number]> = {\n${body}\n};\n`,
);
console.log(`wanted ${wanted.size} city keys, resolved ${Object.keys(out).length}`);
